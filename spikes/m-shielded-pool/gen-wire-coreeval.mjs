// ADR 0014 M7d — generate the LIVE wire deploy: a swingset core-eval that starts the depth-32 shielded pool with
// IST escrow + the depth-32 VKs, and publishes the instance/brand board ids to published.shieldedMeta (a node the
// contract never rewrites) so the relay can build offers without an agoricNames-admin permit.
//
//   node gen-wire-coreeval.mjs <BUNDLE_ID>   → wire-shielded-coreeval.js + wire-shielded-permit.json
import { readFileSync, writeFileSync } from 'node:fs';

const BUNDLE_ID = process.argv[2];
if (!BUNDLE_ID || !BUNDLE_ID.startsWith('b1-')) throw new Error('usage: node gen-wire-coreeval.mjs <b1-bundleId>');

const vk = name => readFileSync(new URL(`./setup-assets/${name}-vk.b64`, import.meta.url), 'utf8').trim();
const TRANSFER_VK = vk('transfer');
const DEPOSIT_VK = vk('deposit');
const WITHDRAW_VK = vk('withdraw');

const coreEval = `/* global E, harden */
/// <reference types="@agoric/vats/src/core/core-eval-env"/>
// ADR 0014 M7d — LIVE wire deploy (generated by gen-wire-coreeval.mjs). Starts the depth-32 shielded pool with
// IST escrow + depth-32 VKs; publishes board ids to published.shieldedMeta for the relay.
const BUNDLE_ID = ${JSON.stringify(BUNDLE_ID)};
const TRANSFER_VK = ${JSON.stringify(TRANSFER_VK)};
const DEPOSIT_VK = ${JSON.stringify(DEPOSIT_VK)};
const WITHDRAW_VK = ${JSON.stringify(WITHDRAW_VK)};

const run = async powers => {
  const { consume: { bridgeManager, zoe, chainStorage, board } } = powers;
  const bm = await bridgeManager;
  const zkVerify = await E(bm).register('zkVerify');
  const mimcHash = await E(bm).register('mimcHash');
  const storageNode = await E(chainStorage).makeChildNode('shieldedEscrow');
  const metaNode = await E(chainStorage).makeChildNode('shieldedMeta');

  const istIssuer = await E(zoe).getFeeIssuer();           // IST: every funded wallet can deposit/withdraw
  const installation = await E(zoe).installBundleID(BUNDLE_ID);
  const { publicFacet, instance } = await E(zoe).startInstance(
    installation,
    harden({ Asset: istIssuer }),                          // issuerKeywordRecord → real IST escrow (M6c)
    harden({}),
    harden({ zkVerify, mimcHash, transferVk: TRANSFER_VK, depositVk: DEPOSIT_VK, withdrawVk: WITHDRAW_VK, storageNode }),
  );

  const brand = await E(publicFacet).getAssetBrand();
  const instanceBoardId = await E(board).getId(instance);
  const brandBoardId = await E(board).getId(brand);
  await E(metaNode).setValue(JSON.stringify({ instanceBoardId, brandBoardId, depth: 32, asset: 'IST' }));
  // state node is published by the contract's own start(); leave it.
};
run;
`;

writeFileSync(new URL('./wire-shielded-coreeval.js', import.meta.url), coreEval);
writeFileSync(new URL('./wire-shielded-permit.json', import.meta.url),
  JSON.stringify({ consume: { bridgeManager: true, zoe: true, chainStorage: true, board: true } }) + '\n');
console.log('wrote wire-shielded-coreeval.js + wire-shielded-permit.json (bundle', BUNDLE_ID.slice(0, 12) + '…)');
